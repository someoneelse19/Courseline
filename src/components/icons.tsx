/** A course's chosen icon, drawn in its color. */
export function CourseIcon({ courseId, className }: { courseId: number; className?: string }) {
  const colorOf = useCourseColors();
  const iconOf = useCourseIcons();
  return (
    <span style={{ color: colorOf(courseId) }} className="flex">
      <CourseIconShape iconKey={iconOf(courseId)} className={className} />
    </span>
  );
}
